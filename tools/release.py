"""Assemble the release package: realdrift_nx.nro + a standalone stage_sd.py.

    python -m tools.release realdrift_nx.nro dist/realdrift_nx-v1.0.0

The released stage_sd.py must run on the user's PC with plain Python (no repository, no
packages), so the `tools.game` import block is replaced by the game identity as literal
values -- still taken from source/game/rd_game.h, at release time.

MIT (see LICENSE).
"""

from __future__ import annotations

import argparse
import inspect
import shutil
import sys
from dataclasses import asdict
from pathlib import Path

from tools import game

STAGE_SD = Path(__file__).with_name("stage_sd.py")
BEGIN = "# >>> game identity"
END = "# <<< game identity"


def standalone_stage_sd(source: str | None = None) -> str:
    """stage_sd.py with the identity block replaced by literals from rd_game.h."""
    source = source if source is not None else STAGE_SD.read_text()
    i, j = source.index(BEGIN), source.index(END)
    j = source.index("\n", j) + 1
    fields = ",\n    ".join(f"{k}={v!r}" for k, v in asdict(game.GAME).items())
    block = (
        f"# game identity (generated by tools/release.py from source/game/rd_game.h)\n"
        f"from types import SimpleNamespace\n"
        f"GAME = SimpleNamespace(\n    {fields},\n)\n"
        f"LITE_PACKAGE = {game.LITE_PACKAGE!r}\n\n\n"
        f"{inspect.getsource(game.obb_name)}"
    )
    return source[:i] + block + source[j:]


def build(nro: Path, out: Path) -> None:
    """Writes the release folder `out`: the .nro, standalone stage_sd.py, config.example.txt."""
    out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(nro, out / nro.name)
    (out / "stage_sd.py").write_text(standalone_stage_sd())
    shutil.copyfile(game.ROOT / "config.example.txt", out / "config.example.txt")


def main(argv: list[str] | None = None) -> int:
    """Command line: build the release folder."""
    ap = argparse.ArgumentParser(description="Assemble the realdrift_nx release package.")
    ap.add_argument("nro", type=Path, help="the built realdrift_nx.nro")
    ap.add_argument("out", type=Path, help="output folder")
    args = ap.parse_args(argv)
    build(args.nro, args.out)
    print(f"release package in {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
